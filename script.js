const supportedLanguages = Object.keys(translations);
const queryLanguage = new URLSearchParams(window.location.search).get("lang");
let savedLanguage = "en";

try {
  savedLanguage = localStorage.getItem("portfolio-language") || "en";
} catch {
  savedLanguage = "en";
}

const initialLanguage = supportedLanguages.includes(queryLanguage)
  ? queryLanguage
  : supportedLanguages.includes(savedLanguage)
    ? savedLanguage
    : "en";

const updateLanguageLinks = (language) => {
  document.querySelectorAll("[data-lang-link]").forEach((link) => {
    if (!link.dataset.baseHref) link.dataset.baseHref = link.getAttribute("href");
    const url = new URL(link.dataset.baseHref, window.location.href);
    url.searchParams.set("lang", language);
    link.href = `${url.pathname}${url.search}${url.hash}`;
  });
};

const applyLanguage = (language, updateAddress = true) => {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  updateLanguageLinks(language);
  const page = document.body.dataset.page || "home";
  document.title = dictionary[`title.${page}`] || dictionary["title.home"];

  try {
    localStorage.setItem("portfolio-language", language);
  } catch {
    // The site still works when storage is unavailable.
  }

  if (updateAddress) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    history.replaceState(null, "", `${url.pathname}${url.search}${url.hash}`);
  }
};

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

applyLanguage(initialLanguage, Boolean(queryLanguage));

const posterGrid = document.querySelector(".poster-grid");

if (posterGrid) {
  const posterCards = Array.from(posterGrid.querySelectorAll(".poster-card"));

  const getPosterRatio = (card) => {
    const image = card.querySelector("img");
    const width = Number(image?.getAttribute("width")) || image?.naturalWidth || 1;
    const height = Number(image?.getAttribute("height")) || image?.naturalHeight || 1;
    return height / width;
  };

  const placePoster = (card, left, top, width) => {
    card.style.left = `${left}px`;
    card.style.top = `${top}px`;
    card.style.width = `${width}px`;
    return top + width * getPosterRatio(card);
  };

  const layoutPosterWall = () => {
    const gridWidth = posterGrid.clientWidth;
    if (!gridWidth) return;

    const viewportWidth = window.innerWidth;
    const columns = viewportWidth <= 640 ? 2 : viewportWidth <= 900 ? 3 : 5;
    const gap = viewportWidth <= 900 ? 8 : 10;
    const columnWidth = (gridWidth - gap * (columns - 1)) / columns;
    const wideCard = posterCards.find((card) => card.classList.contains("poster-card-wide"));
    const regularCards = posterCards.filter((card) => card !== wideCard);
    const columnBottoms = Array(columns).fill(0);

    posterGrid.classList.add("is-masonry");

    if (columns === 5 && regularCards.length >= 8) {
      const topOffsets = [28, 0, 42, 14, 56];
      const thirdColumnBottom = topOffsets[2] + columnWidth * getPosterRatio(regularCards[2]);
      const fourthCardHeight = columnWidth * getPosterRatio(regularCards[3]);
      topOffsets[3] = Math.max(topOffsets[3], thirdColumnBottom - fourthCardHeight);

      regularCards.slice(0, 5).forEach((card, column) => {
        columnBottoms[column] = placePoster(
          card,
          column * (columnWidth + gap),
          topOffsets[column],
          columnWidth
        );
      });

      [0, 1, 4].forEach((column, index) => {
        const card = regularCards[index + 5];
        const top = columnBottoms[column] + gap;
        columnBottoms[column] = placePoster(
          card,
          column * (columnWidth + gap),
          top,
          columnWidth
        );
      });

      if (wideCard) {
        const top = Math.max(columnBottoms[2], columnBottoms[3]) + gap;
        const width = columnWidth * 2 + gap;
        const bottom = placePoster(wideCard, 2 * (columnWidth + gap), top, width);
        columnBottoms[2] = bottom;
        columnBottoms[3] = bottom;
      }
    } else {
      const topOffsets = columns === 3 ? [0, 26, 52] : [0, 24];

      regularCards.slice(0, columns).forEach((card, column) => {
        columnBottoms[column] = placePoster(
          card,
          column * (columnWidth + gap),
          topOffsets[column],
          columnWidth
        );
      });

      regularCards.slice(columns).forEach((card) => {
        const column = columnBottoms.indexOf(Math.min(...columnBottoms));
        const top = columnBottoms[column] + gap;
        columnBottoms[column] = placePoster(card, column * (columnWidth + gap), top, columnWidth);
      });

      if (wideCard) {
        const top = Math.max(...columnBottoms) + gap;
        const bottom = placePoster(wideCard, 0, top, gridWidth);
        columnBottoms.fill(bottom);
      }
    }

    posterGrid.style.height = `${Math.max(...columnBottoms)}px`;
  };

  layoutPosterWall();
  window.addEventListener("resize", layoutPosterWall, { passive: true });
}

